# shellcheck shell=bash
# Shared helpers for scripts/*. Source after setting SCRIPT_DIR:
#   SCRIPT_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
#   source "$SCRIPT_DIR/lib.sh"

GENERATED_PREFIX="# GENERATED by scripts/generate"

die() {
  echo "error: $*" >&2
  exit 1
}

warn() {
  echo "warning: $*" >&2
}

# Print the repo root: the git toplevel containing the scripts, else the scripts' parent dir.
repo_root() {
  local dir=${SCRIPT_DIR:?SCRIPT_DIR not set}
  git -C "$dir" rev-parse --show-toplevel 2>/dev/null || (cd "$dir/.." && pwd)
}

# require_tools [tool...]  (default: kustomize yq). yq must be mikefarah/yq v4.
require_tools() {
  local tools=("$@")
  [[ ${#tools[@]} -gt 0 ]] || tools=(kustomize yq)
  local t
  for t in "${tools[@]}"; do
    command -v "$t" >/dev/null 2>&1 || die "$t not found in PATH"
    if [[ $t == yq ]]; then
      local v
      v=$(yq --version 2>&1 || true)
      [[ $v == *mikefarah* ]] || die "yq must be mikefarah/yq v4 (https://github.com/mikefarah/yq), found: $v"
      [[ $v =~ version\ v?4\. ]] || die "yq must be v4.x, found: $v"
    fi
  done
}

# Temp paths removed on exit. Scripts register paths with cleanup_add instead of setting their own trap.
_CLEANUP=()
cleanup_add() { _CLEANUP+=("$@"); }
_cleanup() {
  local p
  for p in "${_CLEANUP[@]+"${_CLEANUP[@]}"}"; do
    rm -rf -- "$p"
  done
}
trap _cleanup EXIT

# list_clusters: cluster names (dirs under clusters/), sorted.
list_clusters() {
  local d
  for d in "$ROOT"/clusters/*/; do
    [[ -d $d ]] && basename "$d"
  done | LC_ALL=C sort
}

# cluster_fact <cluster> <key>: data.<key> from clusters/<cluster>/facts/facts.yaml (empty if unset).
cluster_fact() {
  local f="$ROOT/clusters/$1/facts/facts.yaml"
  [[ -f $f ]] || die "clusters/$1/facts/facts.yaml not found"
  K=$2 yq -r '.data[strenv(K)] // ""' "$f"
}

# PER_CLUSTER_PROFILE: apps/<app>/profiles/<this>/ holds the app's replacements from the cluster
# facts. It is in every cluster overlay for the app, but no cluster matches it, so it never selects.
PER_CLUSTER_PROFILE=per-cluster

# cluster_profiles <cluster>: the profile names a cluster matches, in the order they apply:
#   <environment>, <clusterType>, <environment>-<clusterType>, <cluster>.
cluster_profiles() {
  local c=$1 ctype envname
  ctype=$(cluster_fact "$c" clusterType) || exit 1
  envname=$(cluster_fact "$c" environment) || exit 1
  [[ -n $ctype ]] || die "clusters/$c/facts/facts.yaml: data.clusterType is not set"
  [[ -n $envname ]] || die "clusters/$c/facts/facts.yaml: data.environment is not set"
  printf '%s\n' "$envname" "$ctype" "$envname-$ctype" "$c"
}

# app_profiles <app> <cluster>: the app's profiles (apps/<app>/profiles/<name>/) that match the
# cluster, in order. Empty if none match, which means the app doesn't run there.
app_profiles() {
  local app=$1 c=$2 p names
  names=$(cluster_profiles "$c") || exit 1
  for p in $names; do
    [[ -d $ROOT/apps/$app/profiles/$p ]] && echo "$p"
  done
  return 0
}

# list_apps: app names (dirs under apps/), sorted.
list_apps() {
  local d
  for d in "$ROOT"/apps/*/; do
    [[ -d $d ]] && basename "$d"
  done | LC_ALL=C sort
}

# resolve_sync <app>: built-in defaults deep-merged with apps/<app>/argocd.yaml sync, as compact JSON.
resolve_sync() {
  local app=$1 defaults="$ROOT/apps/$1/argocd.yaml"
  [[ -f $defaults ]] || die "apps/$app/argocd.yaml not found"
  DFILE=$defaults yq -n -o=json -I=0 \
    '{"automated": {"enabled": true, "prune": true, "selfHeal": true}} * (load(strenv(DFILE)).sync // {})'
}

# env_keys <file>: keys of a KEY=value file (kustomize envs format), in order.
env_keys() {
  awk '$0 !~ /^[[:space:]]*(#|$)/ { sub(/=.*/, ""); print }' "$1"
}

# env_get <file> <key>: value of <key> in a KEY=value file; empty if unset.
env_get() {
  awk -v k="$2" '$0 !~ /^[[:space:]]*(#|$)/ { i = index($0, "="); if (substr($0, 1, i - 1) == k) v = substr($0, i + 1) }
                 END { printf "%s", v }' "$1"
}

# appset_names: ApplicationSet names, from the default revisions file.
appset_names() {
  env_keys "$ROOT/bootstrap/appset-revisions/revisions.env"
}

# appset_revision <cluster> <appset>: the revision the cluster runs for that ApplicationSet
# (its clusters/<cluster>/argocd/revisions.env, else the default).
appset_revision() {
  local v=""
  [[ -f $ROOT/clusters/$1/argocd/revisions.env ]] && v=$(env_get "$ROOT/clusters/$1/argocd/revisions.env" "$2")
  [[ -n $v ]] || v=$(env_get "$ROOT/bootstrap/appset-revisions/revisions.env" "$2")
  echo "$v"
}

# cluster_appsets <cluster>: names of the ApplicationSets the cluster's base includes.
cluster_appsets() {
  kustomize build "$ROOT/clusters/$1/argocd" | yq -r 'select(.kind == "ApplicationSet") | .metadata.name'
}

# commit_has_cluster <sha> <cluster>: true if the commit has generated joins for the cluster.
commit_has_cluster() {
  git -C "$ROOT" ls-tree -d -r --name-only "$1" -- apps 2>/dev/null | grep -qE "^apps/[^/]+/clusters/$2\$"
}
