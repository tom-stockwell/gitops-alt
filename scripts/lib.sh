# shellcheck shell=bash
# Shared helpers for scripts/*. Source after setting SCRIPT_DIR:
#   SCRIPT_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
#   source "$SCRIPT_DIR/lib.sh"

GENERATED_PREFIX="# GENERATED by scripts/generate"

die() {
  echo "error: $*" >&2
  exit 1
}

warn() {
  echo "warning: $*" >&2
}

# Print the repo root: the git toplevel containing the scripts, else the scripts' parent dir.
repo_root() {
  local dir=${SCRIPT_DIR:?SCRIPT_DIR not set}
  git -C "$dir" rev-parse --show-toplevel 2>/dev/null || (cd "$dir/.." && pwd)
}

# require_tools [tool...]  (default: kustomize yq). yq must be mikefarah/yq v4.
require_tools() {
  local tools=("$@")
  [[ ${#tools[@]} -gt 0 ]] || tools=(kustomize yq)
  local t
  for t in "${tools[@]}"; do
    command -v "$t" >/dev/null 2>&1 || die "$t not found in PATH"
    if [[ $t == yq ]]; then
      local v
      v=$(yq --version 2>&1 || true)
      [[ $v == *mikefarah* ]] || die "yq must be mikefarah/yq v4 (https://github.com/mikefarah/yq), found: $v"
      [[ $v =~ version\ v?4\. ]] || die "yq must be v4.x, found: $v"
    fi
  done
}

# Temp paths removed on exit. Scripts register paths with cleanup_add instead of setting their own trap.
_CLEANUP=()
cleanup_add() { _CLEANUP+=("$@"); }
_cleanup() {
  local p
  for p in "${_CLEANUP[@]+"${_CLEANUP[@]}"}"; do
    rm -rf -- "$p"
  done
}
trap _cleanup EXIT

# list_clusters: cluster names (dirs under clusters/), sorted.
list_clusters() {
  local d
  for d in "$ROOT"/clusters/*/; do
    [[ -d $d ]] && basename "$d"
  done | LC_ALL=C sort
}

# cluster_fact <cluster> <key>: data.<key> from clusters/<cluster>/facts/facts.yaml (empty if unset).
cluster_fact() {
  local f="$ROOT/clusters/$1/facts/facts.yaml"
  [[ -f $f ]] || die "clusters/$1/facts/facts.yaml not found"
  K=$2 yq -r '.data[strenv(K)] // ""' "$f"
}

# FACET_KEYS: the cluster facts that pick facets, in the order their facets apply. Every cluster
# must set them all. apps/<app>/facets/<key>/<value>/ matches a cluster whose fact <key> is
# <value>; every key but environment also matches as <value>-<environment>.
FACET_KEYS=(environment role topology region platform)

# CLUSTER_FACET: apps/<app>/facets/<this>/<cluster>/ matches only that cluster (by name). Never
# suffixed; applied last. One-off exceptions; they should rarely exist.
CLUSTER_FACET=cluster

# PER_CLUSTER_FACET: apps/<app>/facets/<this>/ holds the app's replacements from the cluster
# facts. It is in every cluster overlay for the app, but never selects it.
PER_CLUSTER_FACET=per-cluster

# cluster_facets <cluster>: the facets (paths under facets/) a cluster matches, in the order they
# apply: environment/<env>, then <key>/<value> and <key>/<value>-<env> for each other key, then
# cluster/<cluster>.
cluster_facets() {
  local c=$1 k v envname
  envname=$(cluster_fact "$c" environment) || exit 1
  [[ -n $envname ]] || die "clusters/$c/facts/facts.yaml: data.environment is not set"
  echo "environment/$envname"
  for k in "${FACET_KEYS[@]:1}"; do
    v=$(cluster_fact "$c" "$k") || exit 1
    [[ -n $v ]] || die "clusters/$c/facts/facts.yaml: data.$k is not set"
    printf '%s\n' "$k/$v" "$k/$v-$envname"
  done
  echo "$CLUSTER_FACET/$c"
}

# app_facets <app> <cluster>: the app's facets that match the cluster, in order. Empty if none
# match, which means the app doesn't run there.
app_facets() {
  local app=$1 c=$2 f names
  names=$(cluster_facets "$c") || exit 1
  for f in $names; do
    [[ -d $ROOT/apps/$app/facets/$f ]] && echo "$f"
  done
  return 0
}

# join_kustomization <app> <cluster> <facet...>: the generated kustomization.yaml for the app's
# overlay on the cluster, given its matched facets (app_facets). Component order: the facts
# ConfigMap; the facets in cluster_facets order; per-cluster (the app's replacements from the
# facts, so they fill placeholders any facet adds); the cluster facet last, so it can override
# anything.
join_kustomization() {
  local app=$1 c=$2 f last=""
  shift 2
  echo "$GENERATED_PREFIX for clusters/$c — DO NOT EDIT."
  echo "apiVersion: kustomize.config.k8s.io/v1beta1"
  echo "kind: Kustomization"
  echo "resources:"
  echo "- ../../base"
  echo "components:"
  echo "- ../../../../clusters/$c/facts"
  for f in "$@"; do
    if [[ $f == "$CLUSTER_FACET/$c" ]]; then last=$f; else echo "- ../../facets/$f"; fi
  done
  [[ ! -d $ROOT/apps/$app/facets/$PER_CLUSTER_FACET ]] || echo "- ../../facets/$PER_CLUSTER_FACET"
  [[ -z $last ]] || echo "- ../../facets/$last"
}

# ARGOCD_LINK: each overlay's argocd.yaml is a symlink to its app's argocd.yaml. The ApplicationSet's
# git generator reads it, so an Application exists per overlay and gets the app's settings.
ARGOCD_LINK=../../argocd.yaml

