# shellcheck shell=bash
# Shared helpers for scripts/*. Source after setting SCRIPT_DIR:
#   SCRIPT_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
#   source "$SCRIPT_DIR/lib.sh"

GENERATED_PREFIX="# GENERATED by scripts/generate"

die() {
  echo "error: $*" >&2
  exit 1
}

warn() {
  echo "warning: $*" >&2
}

# Print the repo root: the git toplevel containing the scripts, else the scripts' parent dir.
repo_root() {
  local dir=${SCRIPT_DIR:?SCRIPT_DIR not set}
  git -C "$dir" rev-parse --show-toplevel 2>/dev/null || (cd "$dir/.." && pwd)
}

# require_tools [tool...]  (default: kustomize yq). yq must be mikefarah/yq v4.
require_tools() {
  local tools=("$@")
  [[ ${#tools[@]} -gt 0 ]] || tools=(kustomize yq)
  local t
  for t in "${tools[@]}"; do
    command -v "$t" >/dev/null 2>&1 || die "$t not found in PATH"
    if [[ $t == yq ]]; then
      local v
      v=$(yq --version 2>&1 || true)
      [[ $v == *mikefarah* ]] || die "yq must be mikefarah/yq v4 (https://github.com/mikefarah/yq), found: $v"
      [[ $v =~ version\ v?4\. ]] || die "yq must be v4.x, found: $v"
    fi
  done
}

# Temp paths removed on exit. Scripts register paths with cleanup_add instead of setting their own trap.
_CLEANUP=()
cleanup_add() { _CLEANUP+=("$@"); }
_cleanup() {
  local p
  for p in "${_CLEANUP[@]+"${_CLEANUP[@]}"}"; do
    rm -rf -- "$p"
  done
}
trap _cleanup EXIT

# list_clusters: cluster names (dirs under clusters/), sorted.
list_clusters() {
  local d
  for d in "$ROOT"/clusters/*/; do
    [[ -d $d ]] && basename "$d"
  done | LC_ALL=C sort
}

# A file containing `{}`, used in place of a missing profile.
empty_yaml() {
  if [[ -z ${_EMPTY_YAML:-} ]]; then
    _EMPTY_YAML=$(mktemp)
    cleanup_add "$_EMPTY_YAML"
    echo '{}' >"$_EMPTY_YAML"
  fi
  echo "$_EMPTY_YAML"
}

# profile_file <cluster>: path of the profile the cluster extends, or the empty file if none.
profile_file() {
  local c=$1 apps="$ROOT/clusters/$1/apps.yaml" profile
  [[ -f $apps ]] || die "clusters/$c/apps.yaml not found"
  profile=$(yq '.extends // ""' "$apps")
  if [[ -z $profile ]]; then
    empty_yaml
    return
  fi
  [[ -f $ROOT/profiles/$profile.yaml ]] || die "clusters/$c/apps.yaml extends '$profile' but profiles/$profile.yaml does not exist"
  echo "$ROOT/profiles/$profile.yaml"
}

# resolved_apps <cluster>: merged app map (profile + cluster, shallow per-app replace, null removes) as JSON.
resolved_apps() {
  local c=$1 pfile
  pfile=$(profile_file "$c") || exit 1
  yq eval-all -o=json '(select(fi==0).apps // {}) + (select(fi==1).apps // {})
                       | with_entries(select(.value != null))' "$pfile" "$ROOT/clusters/$c/apps.yaml"
}

# resolve_sync <app> <cluster>: argocd.yaml sync * profile entry sync * cluster entry sync, as compact JSON.
resolve_sync() {
  local app=$1 c=$2 pfile defaults="$ROOT/apps/$1/argocd.yaml"
  [[ -f $defaults ]] || die "apps/$app/argocd.yaml not found"
  pfile=$(profile_file "$c") || exit 1
  APP=$app yq eval-all -o=json -I=0 '
      (select(fi==0).sync // {})
    * (select(fi==1).apps[strenv(APP)].sync // {})
    * (select(fi==2).apps[strenv(APP)].sync // {})' \
    "$defaults" "$pfile" "$ROOT/clusters/$c/apps.yaml"
}
