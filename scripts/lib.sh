# shellcheck shell=bash
# Shared helpers for scripts/*. Source after setting SCRIPT_DIR:
#   SCRIPT_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
#   source "$SCRIPT_DIR/lib.sh"

GENERATED_PREFIX="# GENERATED by scripts/generate"

die() {
  echo "error: $*" >&2
  exit 1
}

warn() {
  echo "warning: $*" >&2
}

# Print the repo root: the git toplevel containing the scripts, else the scripts' parent dir.
repo_root() {
  local dir=${SCRIPT_DIR:?SCRIPT_DIR not set}
  git -C "$dir" rev-parse --show-toplevel 2>/dev/null || (cd "$dir/.." && pwd)
}

# require_tools [tool...]  (default: kustomize yq). yq must be mikefarah/yq v4.
require_tools() {
  local tools=("$@")
  [[ ${#tools[@]} -gt 0 ]] || tools=(kustomize yq)
  local t
  for t in "${tools[@]}"; do
    command -v "$t" >/dev/null 2>&1 || die "$t not found in PATH"
    if [[ $t == yq ]]; then
      local v
      v=$(yq --version 2>&1 || true)
      [[ $v == *mikefarah* ]] || die "yq must be mikefarah/yq v4 (https://github.com/mikefarah/yq), found: $v"
      [[ $v =~ version\ v?4\. ]] || die "yq must be v4.x, found: $v"
    fi
  done
}

# Temp paths removed on exit. Scripts register paths with cleanup_add instead of setting their own trap.
_CLEANUP=()
cleanup_add() { _CLEANUP+=("$@"); }
_cleanup() {
  local p
  for p in "${_CLEANUP[@]+"${_CLEANUP[@]}"}"; do
    rm -rf -- "$p"
  done
}
trap _cleanup EXIT

# list_clusters: cluster names (dirs under clusters/), sorted.
list_clusters() {
  local d
  for d in "$ROOT"/clusters/*/; do
    [[ -d $d ]] && basename "$d"
  done | LC_ALL=C sort
}

# cluster_fact <cluster> <key>: data.<key> from clusters/<cluster>/facts/facts.yaml (empty if unset).
cluster_fact() {
  local f="$ROOT/clusters/$1/facts/facts.yaml"
  [[ -f $f ]] || die "clusters/$1/facts/facts.yaml not found"
  K=$2 yq -r '.data[strenv(K)] // ""' "$f"
}

# _layer_profile <cluster> <fact> <profiles subdir>: the profile file a cluster fact selects.
_layer_profile() {
  local c=$1 key=$2 dir=$3 v
  v=$(cluster_fact "$c" "$key") || exit 1
  [[ -n $v ]] || die "clusters/$c/facts/facts.yaml: data.$key is not set"
  [[ -f $ROOT/profiles/$dir/$v.yaml ]] || die "clusters/$c: $key '$v' has no profiles/$dir/$v.yaml"
  echo "$ROOT/profiles/$dir/$v.yaml"
}

# cluster_type_profile / environment_profile <cluster>: the cluster's layer profiles.
cluster_type_profile() { _layer_profile "$1" clusterType cluster-type; }
environment_profile() { _layer_profile "$1" environment environment; }

# resolved_apps <cluster>: the cluster's app map as JSON. Layers, each a shallow per-app replace:
#   1. profiles/cluster-type/<clusterType>.yaml selects apps;
#   2. profiles/environment/<environment>.yaml replaces entries for selected apps only (never
#      adds; null removes);
#   3. clusters/<cluster>/apps.yaml replaces, adds, or removes (null).
resolved_apps() {
  local c=$1 tfile efile
  [[ -f $ROOT/clusters/$c/apps.yaml ]] || die "clusters/$c/apps.yaml not found"
  tfile=$(cluster_type_profile "$c") || exit 1
  efile=$(environment_profile "$c") || exit 1
  TFILE=$tfile EFILE=$efile CFILE="$ROOT/clusters/$c/apps.yaml" yq -n -o=json '
      (load(strenv(TFILE)).apps // {}) as $t
    | (load(strenv(EFILE)).apps // {}) as $e
    | (load(strenv(CFILE)).apps // {}) as $c
    | ($t | to_entries | map(.key as $k | (select($e | has($k)) | .value = $e[$k]) // .) | from_entries)
      + $c
    | with_entries(select(.value != null))'
}

# resolve_sync <app> <cluster>: deep merge, later wins, as compact JSON:
#   built-in defaults * apps/<app>/argocd.yaml sync * cluster-type entry sync
#   * environment entry sync (only if the cluster type selects the app) * cluster entry sync.
resolve_sync() {
  local app=$1 c=$2 tfile efile defaults="$ROOT/apps/$1/argocd.yaml"
  [[ -f $defaults ]] || die "apps/$app/argocd.yaml not found"
  tfile=$(cluster_type_profile "$c") || exit 1
  efile=$(environment_profile "$c") || exit 1
  APP=$app DFILE=$defaults TFILE=$tfile EFILE=$efile CFILE="$ROOT/clusters/$c/apps.yaml" yq -n -o=json -I=0 '
      (load(strenv(TFILE)).apps // {}) as $t
    | {"automated": {"enabled": true, "prune": true, "selfHeal": true}}
    * (load(strenv(DFILE)).sync // {})
    * ($t[strenv(APP)].sync // {})
    * ((select($t | has(strenv(APP))) | load(strenv(EFILE)).apps[strenv(APP)].sync) // {})
    * (load(strenv(CFILE)).apps[strenv(APP)].sync // {})'
}

# env_keys <file>: keys of a KEY=value file (kustomize envs format), in order.
env_keys() {
  awk '$0 !~ /^[[:space:]]*(#|$)/ { sub(/=.*/, ""); print }' "$1"
}

# env_get <file> <key>: value of <key> in a KEY=value file; empty if unset.
env_get() {
  awk -v k="$2" '$0 !~ /^[[:space:]]*(#|$)/ { i = index($0, "="); if (substr($0, 1, i - 1) == k) v = substr($0, i + 1) }
                 END { printf "%s", v }' "$1"
}

# appset_names: ApplicationSet names, from the default revisions file.
appset_names() {
  env_keys "$ROOT/bootstrap/appset-revisions/revisions.env"
}

# appset_revision <cluster> <appset>: the revision the cluster runs for that ApplicationSet
# (its clusters/<cluster>/argocd/revisions.env, else the default).
appset_revision() {
  local v=""
  [[ -f $ROOT/clusters/$1/argocd/revisions.env ]] && v=$(env_get "$ROOT/clusters/$1/argocd/revisions.env" "$2")
  [[ -n $v ]] || v=$(env_get "$ROOT/bootstrap/appset-revisions/revisions.env" "$2")
  echo "$v"
}

# cluster_appsets <cluster>: names of the ApplicationSets the cluster's base includes.
cluster_appsets() {
  kustomize build "$ROOT/clusters/$1/argocd" | yq -r 'select(.kind == "ApplicationSet") | .metadata.name'
}

# commit_has_cluster <sha> <cluster>: true if the commit has generated joins for the cluster.
commit_has_cluster() {
  git -C "$ROOT" ls-tree -d -r --name-only "$1" -- apps 2>/dev/null | grep -qE "^apps/[^/]+/clusters/$2\$"
}
